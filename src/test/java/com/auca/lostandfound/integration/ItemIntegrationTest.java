package com.auca.lostandfound.integration;

import com.auca.lostandfound.dto.ItemRequest;
import com.auca.lostandfound.model.Item;
import com.auca.lostandfound.service.ItemService;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.transaction.annotation.Transactional;

import static org.junit.jupiter.api.Assertions.*;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

/**
 * Integration tests for item reporting and search.
 *
 * Every test hits the full controller → service → repository → H2 stack.
 * Transactions are rolled back after each test so reports from one test
 * never bleed into another.
 *
 * Covers IT-05, IT-06, IT-07, IT-11, IT-12.
 */
@SpringBootTest
@AutoConfigureMockMvc
@ActiveProfiles("test")
@Transactional
@DisplayName("Items — reporting and search (IT-05 to IT-07, IT-11 to IT-12)")
class ItemIntegrationTest {

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private ItemService itemService;

    @Autowired
    private ObjectMapper objectMapper;

    // ── IT-05 — create a Found report ─────────────────────────────────────────

    /**
     * IT-05
     * A student who finds something on campus should be able to submit a
     * Found report.  The database row must carry the type "FOUND", a
     * unique ItemId generated by the system, and the creator's UserId.
     */
    @Test
    @DisplayName("IT-05 | submitting a Found report persists it correctly in the database")
    void createFoundReport_persistsWithCorrectTypeAndOwner() throws Exception {
        // We also verify via the service layer that the saved object is correct
        ItemRequest req = new ItemRequest(
            "Black wireless mouse",
            "Electronics",
            "Found near the main entrance desk",
            "Library",
            "2026-11-03",
            "FOUND"
        );

        Item saved = itemService.createReport(req, 1L /* creatorUserId = Student 1 */);

        // The item must exist and carry the right report type
        assertNotNull(saved, "createReport should return the saved item, not null.");
        assertEquals("FOUND",     saved.getReportType(),    "Report type should be FOUND.");
        assertEquals("AVAILABLE", saved.getStatus(),        "A new report starts as AVAILABLE.");
        assertEquals(1L,          saved.getCreatorUserId(), "Creator UserId should be 1.");

        // Also verify the HTTP layer accepts and returns 201 Created
        mockMvc.perform(post("/api/items")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(req))
                .header("X-User-Id", "1"))   // authenticated student
               .andExpect(status().isCreated())
               .andExpect(jsonPath("$.reportType").value("FOUND"))
               .andExpect(jsonPath("$.status").value("AVAILABLE"));
    }

    // ── IT-06 — create a Lost report ──────────────────────────────────────────

    /**
     * IT-06
     * A student who lost something should be able to post a Lost report
     * and have all required fields stored accurately.
     */
    @Test
    @DisplayName("IT-06 | submitting a Lost report persists it with type LOST")
    void createLostReport_persistsWithCorrectType() throws Exception {
        ItemRequest req = new ItemRequest(
            "Blue notebook",
            "Books",
            "A5 spiral notebook with blue cover and my name on the first page",
            "Classroom B12",
            "2026-11-02",
            "LOST"
        );

        Item saved = itemService.createReport(req, 1L);

        assertEquals("LOST",      saved.getReportType(), "Report type should be LOST.");
        assertEquals("AVAILABLE", saved.getStatus(),     "Status should default to AVAILABLE.");

        mockMvc.perform(post("/api/items")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(req))
                .header("X-User-Id", "1"))
               .andExpect(status().isCreated())
               .andExpect(jsonPath("$.reportType").value("LOST"));
    }

    // ── IT-07 — keyword search ────────────────────────────────────────────────

    /**
     * IT-07
     * Searching for "mouse" should surface the black wireless mouse report
     * that was just submitted, and must not return unrelated items like
     * notebooks or student ID cards.
     */
    @Test
    @DisplayName("IT-07 | searching by keyword 'mouse' returns matching reports only")
    void keywordSearch_returnsMatchingReportsAndExcludesOthers() throws Exception {
        // Post a Found mouse report and a Lost notebook report
        ItemRequest mouseReport = new ItemRequest(
            "Black wireless mouse", "Electronics",
            "Found near the main desk", "Library", "2026-11-03", "FOUND");
        ItemRequest notebookReport = new ItemRequest(
            "Blue notebook", "Books",
            "Left in Classroom B12", "Classroom B12", "2026-11-02", "LOST");

        mockMvc.perform(post("/api/items")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(mouseReport))
                .header("X-User-Id", "1"))
               .andExpect(status().isCreated());

        mockMvc.perform(post("/api/items")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(notebookReport))
                .header("X-User-Id", "1"))
               .andExpect(status().isCreated());

        // Search for 'mouse' — only the mouse report should come back
        mockMvc.perform(get("/api/items/search")
                .param("keyword", "mouse"))
               .andExpect(status().isOk())
               .andExpect(jsonPath("$").isArray())
               .andExpect(jsonPath("$[0].name").value("Black wireless mouse"))
               // The notebook must not appear in results for 'mouse'
               .andExpect(jsonPath("$[?(@.name == 'Blue notebook')]").doesNotExist());
    }

    // ── IT-11 — filtered search by type and category ──────────────────────────

    /**
     * IT-11
     * When a student filters by type=FOUND and category=Electronics,
     * only Found Electronics items should come back — not Lost ones and
     * not items from other categories.
     */
    @Test
    @DisplayName("IT-11 | filtering by type=FOUND and category=Electronics narrows results correctly")
    void filterByTypeAndCategory_returnsOnlyMatchingItems() throws Exception {
        // Create a FOUND Electronics item
        ItemRequest foundElectronics = new ItemRequest(
            "Black wireless mouse", "Electronics",
            "Found near the main desk", "Library", "2026-11-03", "FOUND");

        // Create a LOST Books item — should not appear in the filtered results
        ItemRequest lostBook = new ItemRequest(
            "Blue notebook", "Books",
            "Left in Classroom B12", "Classroom B12", "2026-11-02", "LOST");

        mockMvc.perform(post("/api/items")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(foundElectronics))
                .header("X-User-Id", "1"))
               .andExpect(status().isCreated());

        mockMvc.perform(post("/api/items")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(lostBook))
                .header("X-User-Id", "1"))
               .andExpect(status().isCreated());

        mockMvc.perform(get("/api/items")
                .param("type",     "FOUND")
                .param("category", "Electronics"))
               .andExpect(status().isOk())
               .andExpect(jsonPath("$").isArray())
               // Every item in the response must be FOUND and in Electronics
               .andExpect(jsonPath("$[?(@.reportType != 'FOUND')]").doesNotExist())
               .andExpect(jsonPath("$[?(@.category != 'Electronics')]").doesNotExist());
    }

    // ── IT-12 — search with no matches ────────────────────────────────────────

    /**
     * IT-12
     * When a student searches for something that simply does not exist,
     * the system should respond gracefully with an empty list — not a
     * 500 error or a confusing null response.
     */
    @Test
    @DisplayName("IT-12 | searching for a non-existent keyword returns an empty list cleanly")
    void searchForNonExistentKeyword_returnsEmptyList() throws Exception {
        mockMvc.perform(get("/api/items/search")
                .param("keyword", "NonExistentItemXYZ"))
               .andExpect(status().isOk())
               .andExpect(jsonPath("$").isArray())
               .andExpect(jsonPath("$").isEmpty());
    }
}
